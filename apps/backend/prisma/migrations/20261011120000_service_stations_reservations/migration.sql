-- DATA IMPACT:
-- Tables affected: products (new requires_station column), bookings, orders, order_items, plus 14 new service tables.
-- Expected row changes: existing products receive requires_station=false; existing bookings/orders/order_items keep NULL links.
-- Destructive operations: none.
-- FK/cascade risk: new FKs use RESTRICT/NO ACTION; no cascading business deletes.
-- Idempotency: DDL guarded with IF NOT EXISTS / catalog checks. Exclusion constraint is guarded by pg_constraint.
-- Approval: additive A.2 contract; future active booking reconciliation remains required before enabling station-required services.

