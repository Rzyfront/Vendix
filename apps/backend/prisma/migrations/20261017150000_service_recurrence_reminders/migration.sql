-- DATA IMPACT:
-- Tables affected: products (nullable recurrence_interval_days), new service_reminder_logs.
-- Expected row changes: existing products retain NULL recurrence_interval_days; no existing reminder logs.
-- Destructive operations: none.
-- FK/cascade risk: none.
-- Idempotency: additive column/table/indexes use IF NOT EXISTS; constraints guarded by pg_constraint.
-- Approval: implementation continuation.

ALTER TABLE "products" ADD COLUMN IF NOT EXISTS "recurrence_interval_days" INTEGER;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'products_recurrence_interval_days_check'
  ) THEN
    ALTER TABLE "products"
      ADD CONSTRAINT "products_recurrence_interval_days_check"
      CHECK ("recurrence_interval_days" IS NULL OR "recurrence_interval_days" BETWEEN 1 AND 365);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS "service_reminder_logs" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "store_id" INTEGER NOT NULL,
  "customer_id" INTEGER NOT NULL,
  "product_id" INTEGER NOT NULL,
  "source_order_id" INTEGER NOT NULL,
  "due_date" DATE NOT NULL,
  "channel" VARCHAR(20) NOT NULL DEFAULT 'notification',
  "status" VARCHAR(20) NOT NULL DEFAULT 'pending',
  "sent_at" TIMESTAMPTZ(6),
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'service_reminder_logs_store_id_fkey'
  ) THEN
    ALTER TABLE "service_reminder_logs"
      ADD CONSTRAINT "service_reminder_logs_store_id_fkey"
      FOREIGN KEY ("store_id") REFERENCES "stores"("id")
      ON DELETE RESTRICT ON UPDATE CASCADE;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "service_reminder_logs_store_customer_product_order_key"
  ON "service_reminder_logs" ("store_id", "customer_id", "product_id", "source_order_id");

CREATE INDEX IF NOT EXISTS "service_reminder_logs_store_status_idx"
  ON "service_reminder_logs" ("store_id", "status");
