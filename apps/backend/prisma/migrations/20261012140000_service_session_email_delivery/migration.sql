-- DATA IMPACT:
-- Tables affected: service_sessions (nullable contact_email), new service_session_email_deliveries.
-- Expected row changes: existing sessions retain NULL contact_email; no existing delivery rows.
-- Destructive operations: none.
-- FK/cascade risk: delivery rows restrict deletion of their session/token records.
-- Idempotency: additive columns/table/indexes use IF NOT EXISTS; constraints are catalog-guarded.
-- Approval: implementation continuation; no production data is changed by this migration itself.

ALTER TABLE "service_sessions" ADD COLUMN IF NOT EXISTS "contact_email" VARCHAR(255);
ALTER TABLE "service_progress_events" ADD COLUMN IF NOT EXISTS "metadata" JSONB;

CREATE TABLE IF NOT EXISTS "service_session_email_deliveries" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "store_id" INTEGER NOT NULL,
  "session_id" INTEGER NOT NULL,
  "token_id" INTEGER NOT NULL,
  "idempotency_key" VARCHAR(120) NOT NULL,
  "recipient" VARCHAR(255) NOT NULL,
  "status" VARCHAR(20) NOT NULL DEFAULT 'pending',
  "attempt_count" INTEGER NOT NULL DEFAULT 0,
  "provider_message_id" VARCHAR(255),
  "last_error" VARCHAR(500),
  "sent_at" TIMESTAMPTZ(6),
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "service_session_email_deliveries_idempotency_key_key" UNIQUE ("idempotency_key"),
  CONSTRAINT "service_session_email_deliveries_token_id_key" UNIQUE ("token_id"),
  CONSTRAINT "service_session_email_deliveries_session_store_fkey" FOREIGN KEY ("store_id", "session_id") REFERENCES "service_sessions"("store_id", "id") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "service_session_email_deliveries_token_fkey" FOREIGN KEY ("token_id") REFERENCES "service_session_tokens"("id") ON DELETE RESTRICT ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS "service_session_email_deliveries_store_session_status_idx" ON "service_session_email_deliveries"("store_id", "session_id", "status");
