/** Spanish `LEEME.txt` at the root of every Flows export. */
export function buildExportReadme(storeName: string, generatedAt: Date): string {
  const date = new Intl.DateTimeFormat('es-CO', {
    dateStyle: 'long',
    timeStyle: 'short',
    timeZone: 'America/Bogota',
  }).format(generatedAt);
  return [
    'EXPORTACIÓN COMPLETA DE FLUJOS',
    '==============================',
    '',
    `Tienda: ${storeName}`,
    `Generada: ${date} (hora de Colombia) · ${generatedAt.toISOString()}`,
    '',
    'Este ZIP trae toda la información de Flujos y Documentos de tu tienda para que la conserves fuera de Vendix.',
    'Los archivos .jsonl tienen un registro JSON por línea; los .json, un solo registro.',
    '',
    'QUÉ HAY EN CADA CARPETA',
    '-----------------------',
    '- manifest.json: cuántos registros hay de cada cosa, cada archivo del ZIP con su tamaño y su huella SHA-256, los archivos que no se pudieron incluir (y por qué) y el resultado de verificar la auditoría.',
    '- flujos/: las definiciones de tus flujos con sus permisos de acceso (definiciones.jsonl) y cada versión publicada (versiones/<flujo>-v<número>.json).',
    '- solicitudes/: las solicitudes (instancias.jsonl) con sus eventos, tareas, votos, comentarios y compuertas de aprobación.',
    '- expedientes/: los expedientes y sus elementos, la lista de archivos con sus huellas y, en expedientes/archivos/, los archivos adjuntos vigentes con el nombre <id>-<nombre>.',
    '- registros/: las colecciones personalizadas y sus registros.',
    '- documentos/: plantillas y sus versiones, documentos emitidos, solicitudes de firma, firmantes y evidencia de firma; en documentos/archivos/, los PDF emitidos, los sellados y las imágenes de firma.',
    '- auditoria/audit.jsonl: el registro de auditoría de la tienda (definiciones, decisiones, accesos a documentos, secretos y exportaciones), con el hash de cada registro.',
    '- integraciones/: los webhooks de salida (solo dirección y eventos), las entradas por llamada (sin claves) y los NOMBRES de los secretos.',
    '',
    'LO QUE NO INCLUYE',
    '-----------------',
    '- Nunca incluye los valores de los secretos, los secretos de firma de webhooks y entradas, los tokens de enlaces ni las claves de API.',
    '- Los archivos eliminados o purgados por retención no se pueden incluir; quedan listados en manifest.json (skipped_files).',
    '',
    'CÓMO VERIFICAR LA AUDITORÍA',
    '---------------------------',
    'Cada registro de auditoria/audit.jsonl enlaza con el anterior: entry_hash = SHA-256 (en hexadecimal) de prev_hash + el JSON canónico del registro.',
    '1. Ordena los registros por seq. El primero tiene prev_hash nulo (se toma como texto vacío) y seq = 1; cada seq sube de uno en uno.',
    '2. El JSON canónico es un objeto con las llaves ordenadas alfabéticamente y sin espacios, con estos campos: store_id, seq (como texto), category, action, actor_type, actor_id, actor_label, target_type, target_id, definition_id, instance_id, summary, details, ip_address, user_agent y created_at (fecha ISO 8601 en UTC).',
    '3. Calcula SHA-256(prev_hash + JSON canónico) y compáralo con entry_hash; el prev_hash de cada registro debe ser el entry_hash del anterior.',
    '4. Si alguien alteró, quitó o insertó un registro, la cadena se rompe en ese punto.',
    'Vendix ya hizo esta verificación al generar el ZIP: su resultado está en manifest.json, campo audit_chain (valid, count y last_hash).',
    '',
  ].join('\n');
}
